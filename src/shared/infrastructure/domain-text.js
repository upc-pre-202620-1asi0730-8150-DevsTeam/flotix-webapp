import { i18n } from '@/internationalization/i18n.js'

/**
 * Display helpers for values that are stored in Spanish (statuses, vehicle types,
 * generated alert texts) so the UI can show them in the active language.
 * The stored value is never changed: only what the user reads.
 */
const t = (key, params) => i18n.global.t(key, params)
const te = (key) => i18n.global.te(key)

export function statusLabel(status) {
  return te(`status.${status}`) ? t(`status.${status}`) : status
}

export function vehicleTypeLabel(type) {
  return te(`vehicleTypes.${type}`) ? t(`vehicleTypes.${type}`) : type
}

export function productLabel(sku, fallback) {
  return te(`commerce.products.${sku}`) ? t(`commerce.products.${sku}`) : (fallback ?? sku)
}

/** Alert types are generated as Spanish text by the alerts service; translate the known ones. */
export function alertTypeLabel(type) {
  let m = /^Exceso de velocidad \((\d+) km\/h\)$/.exec(type)
  if (m) return t('alerts.types.speed', { speed: m[1] })
  m = /^Mantenimiento próximo \((\d+)% de kilometraje\)$/.exec(type)
  if (m) return t('alerts.types.maintenance', { pct: m[1] })
  return type
}

/** Notification messages generated by Flotix (also stored in Spanish). Free text is left untouched. */
export function notificationMessage(message) {
  let m = /^El vehículo (.+) superó el límite de velocidad: (\d+) km\/h\.$/.exec(message)
  if (m) return t('alerts.messages.speed', { plate: m[1], speed: m[2] })
  m = /^El vehículo (.+) alcanzó el (\d+)% del kilometraje de revisión preventiva\.$/.exec(message)
  if (m) return t('alerts.messages.maintenance', { plate: m[1], pct: m[2] })
  m = /^Nueva incidencia reportada: ([\s\S]+)$/.exec(message)
  if (m) return t('alerts.messages.incident', { description: m[1] })
  return message
}
